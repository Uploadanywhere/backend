import typing as t


class DataMapper[E, C](t.Protocol):
    def __init__(self, connection: C) -> None: ...

    def update_all(self, users: list[E]) -> None: ...

    def add_all(self, users: list[E]) -> None: ...

    def delete_all(self, users: list[E]) -> None: ...


class AsyncDataMapper[E, C](t.Protocol):
    def __init__(self, connection: C) -> None: ...

    async def update_all(self, users: list[E]) -> None: ...

    async def add_all(self, users: list[E]) -> None: ...

    async def delete_all(self, users: list[E]) -> None: ...
